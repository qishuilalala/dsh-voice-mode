import assert from 'node:assert/strict'
import { voiceClient } from './helpers/voice-client.mjs'
const c=await voiceClient()
try {
  c.bus.setUi({boot:{...c.bus.ui.boot,readAloud:'always'}})
  c.bus.setFocusedSession('A','one')
  c.emit('focus',{sessionId:'A',tabId:'tab'})
  c.audio('A',0)
  assert.equal(c.bus.ui.playing,true)
  c.emit('focus',{sessionId:null,tabId:null})
  assert.equal(c.bus.ui.playing,true,'断连清焦点广播不得停止已在播放的句子')
  assert.equal(c.audios[0].paused,false)
  c.emit('open',{})
  assert.deepEqual(c.requests.filter(r=>r.url.endsWith('/focus')).at(-1).body,{sessionId:'A',tabId:'tab'},'重连必须补报本标签页焦点')
  c.emit('focus',{sessionId:null,tabId:null})
  assert.equal(c.bus.ui.playing,true,'重连初始空焦点不得停播')
  c.emit('focus',{sessionId:'A',tabId:'tab'})
  c.audio('A',1);c.finishAudio()
  assert.equal(c.bus.ui.playing,true,'补报焦点后后续句子继续播放')
  c.bus.setFocusedSession('B','two')
  assert.equal(c.bus.ui.playing,false,'切会话应立即停止本地播放，不等待 HTTP/SSE')
  assert.equal(c.audios[0].paused,true)
  c.emit('focus',{sessionId:'B',tabId:'tab'});c.audio('B',2)
  assert.equal(c.bus.ui.playingCaption,'B')
  c.bus.setFocusedSession(null,'one')
  assert.equal(c.bus.ui.playing,true,'旧实例卸载不能停止当前实例的 B')
  c.emit('focus',{sessionId:'B',tabId:'other'})
  assert.equal(c.bus.ui.playing,false,'跨标签页转移焦点也必须停播')
  c.emit('focus',{sessionId:'B',tabId:'tab'});c.audio('B',3)
  assert.equal(c.bus.ui.playing,true)
  c.bus.setFocusedSession(null,'two')
  assert.equal(c.bus.ui.playing,false,'最后一个持有者卸载即停播')
  c.bus.setFocusedSession('A','three');c.emit('focus',{sessionId:'A',tabId:'tab'})
  c.audio('A',0)
  assert.equal(c.bus.ui.playing,false,'切回 A 也不得重播旧句')
  c.audio('A',4)
  assert.equal(c.bus.ui.playingCaption,'A','A 新回合越过拒绝线后正常播放')
  await c.bus.enter('A')
  c.emit('mode',{active:'A',ownerTabId:'tab'})
  c.emit('focus',{sessionId:'B',tabId:'other'})
  c.audio('A',5)
  assert.equal(c.bus.ui.playing,true)
  c.emit('focus',{sessionId:null,tabId:null})
  assert.equal(c.bus.ui.playing,true,'其它焦点标签页断连不得停止本页语音会话')
  c.emit('focus',{sessionId:'A',tabId:'tab'})
  c.emit('open',{});c.emit('focus',{sessionId:null,tabId:null})
  assert.equal(c.bus.ui.playing,true,'语音 owner 重连收到空焦点也不得停播')
  console.log('  ✓ 本地切换、跨 tab 焦点、实例卸载均正确停播且不误伤存活实例')
} finally { c.close() }
