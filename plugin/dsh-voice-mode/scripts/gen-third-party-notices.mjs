#!/usr/bin/env node
/**
 * 生成 THIRD_PARTY_NOTICES.md：列出被内联进 lib/msedge-tts.cjs 的全部第三方包及其许可文本。
 * 依据 build.mjs 写出的 metafile（lib/.msedge-tts.meta.json）——先 `node build.mjs` 再运行本脚本。
 * 用法：node scripts/gen-third-party-notices.mjs [--check]   --check：只校验已提交的文件是否覆盖全部被内联的包。
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { join, dirname, resolve } from 'node:path'

const root = resolve(dirname(new URL(import.meta.url).pathname), '..')
const meta = JSON.parse(readFileSync(join(root, 'lib/.msedge-tts.meta.json'), 'utf8'))

/** 从 metafile 的输入路径提取包根目录（兼容 pnpm 的 .pnpm 虚拟存储路径）。 */
const pkgRoots = new Set()
for (const input of Object.keys(meta.inputs)) {
  const m = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//g)
  if (!m) continue
  // 取最后一个 node_modules/<pkg> 段
  const idx = input.lastIndexOf('node_modules/')
  const rest = input.slice(idx + 'node_modules/'.length).split('/')
  const name = rest[0].startsWith('@') ? `${rest[0]}/${rest[1]}` : rest[0]
  pkgRoots.add(input.slice(0, idx + 'node_modules/'.length) + name)
}
const pkgs = [...pkgRoots].map((dir) => {
  const pj = JSON.parse(readFileSync(join(root, dir, 'package.json'), 'utf8'))
  const licFile = readdirSync(join(root, dir)).find((f) => /^(license|licence|copying)(\.|$)/i.test(f))
  return {
    name: pj.name, version: pj.version, license: typeof pj.license === 'string' ? pj.license : JSON.stringify(pj.license),
    repo: typeof pj.repository === 'string' ? pj.repository : pj.repository?.url ?? '',
    text: licFile ? readFileSync(join(root, dir, licFile), 'utf8').trim() : '(package ships no license file; see its repository)',
  }
}).filter((p, i, arr) => arr.findIndex((q) => q.name === p.name && q.version === p.version) === i) // 同一包可能经两条路径出现
  .sort((a, b) => a.name.localeCompare(b.name))

const head = `# Third-party notices

\`lib/msedge-tts.cjs\` inlines the following third-party packages (they are not installed as runtime dependencies; see the
comment in \`build.mjs\` for why). Their licenses are reproduced below. Generated by \`scripts/gen-third-party-notices.mjs\`.

| Package | Version | License |
| --- | --- | --- |
${pkgs.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`).join('\n')}
`
const body = pkgs.map((p) => `\n## ${p.name} ${p.version}\n\n- License: ${p.license}${p.repo ? `\n- Source: ${p.repo.replace(/^git\+/, '')}` : ''}\n\n\`\`\`\n${p.text}\n\`\`\`\n`).join('')
const out = head + body

const file = join(root, 'THIRD_PARTY_NOTICES.md')
if (process.argv.includes('--check')) {
  const cur = existsSync(file) ? readFileSync(file, 'utf8') : ''
  const missing = pkgs.filter((p) => !cur.includes(`## ${p.name} ${p.version}`)).map((p) => `${p.name}@${p.version}`)
  if (missing.length) { console.error('THIRD_PARTY_NOTICES.md 缺少：' + missing.join(', ')); process.exit(1) }
  console.log(`✓ THIRD_PARTY_NOTICES.md 覆盖全部 ${pkgs.length} 个内联包`)
} else {
  writeFileSync(file, out, 'utf8')
  console.log(`写入 THIRD_PARTY_NOTICES.md：${pkgs.length} 个包（${pkgs.map((p) => p.name).join(', ')}）`)
}
